-- Ejercicios por módulo.
-- `format` = ExerciseFormat (prediction, ordering, snippet-pick, bug-hunt,
-- matching, context-dropdown, true-false); NULL = legacy [INPUT_N].
-- `format_payload` = UN jsonb con el payload del formato (el cliente lo
-- deserializa al tipo concreto usando `format` como discriminador).
CREATE TABLE IF NOT EXISTS public.exercises (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_key       text NOT NULL REFERENCES public.modules(key) ON DELETE CASCADE,
  exercise_ref     int NOT NULL,                 -- id original dentro del módulo
  title            text NOT NULL,
  stars            int NOT NULL DEFAULT 1,
  category         text,
  step             int,
  description      text,
  objective        text,
  tags             text[] NOT NULL DEFAULT '{}',
  file_name        text,
  instruction      text,
  theory           text,
  explanation_text text,
  code_snippet     text NOT NULL,
  inputs           jsonb NOT NULL DEFAULT '{}',  -- mapa INPUT_N -> ExpectedAnswer
  complete_code    text,
  simulation       jsonb,                        -- ShellScenario (solo Bash)
  format           text,
  format_payload   jsonb,
  position         int NOT NULL DEFAULT 0,
  is_published     boolean NOT NULL DEFAULT true,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT exercises_module_ref_key UNIQUE (module_key, exercise_ref)
);

-- Pistas progresivas (general → concreta) para el sistema de hints pedagógicos.
-- `jsonb` mantiene el array de strings, coherente con `inputs` y `format_payload`.
ALTER TABLE public.exercises

-- Perfil ligado a auth.users (se crea por trigger, ver sección 4).
CREATE TABLE IF NOT EXISTS public.profiles (
  id           uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email        text NOT NULL,
  display_name text,
  avatar_url   text,
  role         text NOT NULL DEFAULT 'student' CHECK (role IN ('admin', 'student')),
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Cursos padre (los grupos históricos del catálogo).
CREATE TABLE IF NOT EXISTS public.courses (
  key          text PRIMARY KEY,
  name         text NOT NULL,
  description  text,
  icon         text,
  color        text,
  position     int NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT true,
  updated_at   timestamptz NOT NULL DEFAULT now()
);

-- Módulos/temas pertenecientes a un curso padre.
-- `description` mapea el campo `desc` del modelo TS.
CREATE TABLE IF NOT EXISTS public.modules (
  key          text PRIMARY KEY,
  course_key   text NOT NULL REFERENCES public.courses(key) ON UPDATE CASCADE ON DELETE RESTRICT,
  name         text NOT NULL,
  icon         text,
  badge        text,
  color        text,
  "group"      text,
  description  text,
  topics       text[] NOT NULL DEFAULT '{}',
  position     int NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT true,
  updated_at   timestamptz NOT NULL DEFAULT now()
);


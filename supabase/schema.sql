-- Catálogo público seguro: expone temario y metadatos, nunca contenido que
-- revele código, respuestas o soluciones.
CREATE OR REPLACE FUNCTION public.get_public_course_curriculum(
  p_course_key text DEFAULT NULL
)
RETURNS TABLE (
  course_key text,
  course_name text,
  course_description text,
  course_icon text,
  course_color text,
  course_position int,
  curriculum jsonb
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT
    c.key,
    c.name,
    c.description,
    c.icon,
    c.color,
    c.position,
    COALESCE(
      jsonb_agg(
        jsonb_build_object(
          'key', m.key,
          'name', m.name,
          'icon', m.icon,
          'badge', m.badge,
          'color', m.color,
          'description', m.description,
          'topics', m.topics,
          'position', m.position,
          'exercises', (
            SELECT COALESCE(
              jsonb_agg(
                jsonb_build_object(
                  'exercise_ref', e.exercise_ref,
                  'title', e.title,
                  'stars', e.stars,
                  'category', e.category,
                  'step', e.step,
                  'description', e.description,
                  'objective', e.objective,
                  'tags', e.tags,
                  'position', e.position
                )
                ORDER BY e.position, e.exercise_ref
              ),
              '[]'::jsonb
            )
            FROM public.exercises e
            WHERE e.module_key = m.key
              AND e.is_published
          )
        )
        ORDER BY m.position, m.key
      ) FILTER (WHERE m.key IS NOT NULL),
      '[]'::jsonb
    )
  FROM public.courses c
  LEFT JOIN public.modules m
    ON m.course_key = c.key
   AND m.is_published
  WHERE c.is_published
    AND (p_course_key IS NULL OR c.key = p_course_key)
  GROUP BY c.key, c.name, c.description, c.icon, c.color, c.position
  ORDER BY c.position, c.key;
$$;

